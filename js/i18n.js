const I18N = {
  lang: localStorage.getItem("lemny-lang") || "ro",
  t(key) {
    return translations[this.lang]?.[key] ?? translations.ro[key] ?? key;
  },
  setLang(lang) {
    if (!translations[lang]) return;
    this.lang = lang;
    localStorage.setItem("lemny-lang", lang);
    document.documentElement.lang = lang;
    this.apply();
  },
  apply() {
    document.querySelectorAll("[data-i18n]").forEach((el) => {
      const key = el.getAttribute("data-i18n");
      const value = this.t(key);
      if (el.tagName === "INPUT" || el.tagName === "TEXTAREA") return;
      el.textContent = value;
    });
    document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
      el.setAttribute("placeholder", this.t(el.getAttribute("data-i18n-placeholder")));
    });
    document.querySelectorAll("[data-lang-btn]").forEach((btn) => {
      btn.classList.toggle("is-active", btn.getAttribute("data-lang-btn") === this.lang);
      btn.setAttribute("aria-pressed", String(btn.getAttribute("data-lang-btn") === this.lang));
    });
    const titleMap = {
      ro: "Lemny Case — Case mici din lemn în România",
      de: "Lemny Case — Kleine Holzhäuser in Rumänien",
      en: "Lemny Case — Small wooden homes in Romania",
    };
    document.title = titleMap[this.lang] || titleMap.ro;
  },
};
